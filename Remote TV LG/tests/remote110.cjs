'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),acorn=require('acorn');
const root=path.resolve(__dirname,'..');
const file=p=>fs.readFileSync(root+'/'+p);
const txt=p=>file(p).toString('utf8');
const manifest=JSON.parse(txt('manifest.json'));
assert.equal(manifest.version,'1.1.0');
assert.equal(manifest.schema,1);
assert.deepEqual(manifest,JSON.parse(txt('manifest.1.1.0.json')));
assert.equal(manifest.path,'releases/1.1.0/player.html');
const embeddedSource=file('src/lg-1.0.3.original.html'),published=file(manifest.path);
assert.ok(embeddedSource.equals(published),'LG 1.1.0 runtime must remain byte-exact to received 1.0.3 IPK');
assert.equal(published.length,131345);
assert.equal(crypto.createHash('sha256').update(published).digest('hex'),'c030ded142aa78dabf90040eb4b3a04475985f65e671a4e1fa946ff8482c263f');
assert.equal(manifest.bytes,published.length);
assert.equal(manifest.sha256,crypto.createHash('sha256').update(published).digest('hex'));
const html=published.toString('utf8'),script=html.match(/<script>([\s\S]*?)<\/script>/);
assert.ok(script);
acorn.parse(script[1],{ecmaVersion:5});
for (const name of ['AuraBoot','aura-ready','player_api.php','LGNative','beta.progress.','beta.continue.'])assert.ok(html.includes(name),name);
assert.equal(txt('version').trim(),'1.0.2','An untested LG release cannot activate the remote marker');
assert.ok(txt('app/launcher.js').includes('versionNum(marker)'),'The existing LG 1.0.2 launcher must be able to stage newer versions');
console.log('PASS LG 1.1.0 staged: original uploaded 1.0.3 IPK player byte-exact, UTF8 SHA256, ES5, account storage, no launcher replacement');